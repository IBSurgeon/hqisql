
SET ECHO ON;
CREATE DATABASE 'imp.fdb' DEFAULT CHARACTER SET UTF8;
CREATE TABLE T (ID INT PRIMARY KEY, D DATE, N NUMERIC(10,2), B BLOB SUB_TYPE TEXT, S VARCHAR(10), BO BOOLEAN);
CREATE TABLE P (NAME VARCHAR(10), AMOUNT NUMERIC(10,2), X COMPUTED BY (NAME || '!'), ID INT GENERATED ALWAYS AS IDENTITY);
CREATE TABLE M (ID INT, S VARCHAR(20));
CREATE VIEW V AS SELECT NAME, AMOUNT FROM P;
COMMIT;

-- header names the columns
IMPORT INTO T FROM CSV 'a.csv' OPTIONS (HEADER);
SELECT ID, D, N, B, S, BO, S IS NULL AS SNULL FROM T ORDER BY ID;

-- stops at the bad row; rows before stay
IMPORT INTO T (ID, D) FROM CSV 'err.csv';
SELECT ID, D FROM T WHERE ID >= 10 ORDER BY ID;

-- ERRORS: bad rows to err2.csv.bad
IMPORT INTO T (ID, D) FROM CSV 'err2.csv' OPTIONS (ERRORS = 5, BATCH = 3);
SELECT ID, D FROM T WHERE ID >= 20 ORDER BY ID;

-- too many errors
DELETE FROM T WHERE ID >= 20;
IMPORT INTO T (ID, D) FROM CSV 'err2.csv' OPTIONS (ERRORS = 1);
SELECT COUNT(*) FROM T WHERE ID >= 20;

-- the columns of the table (no computed, no identity always), WIN1251, decimal comma
IMPORT INTO P FROM CSV 'w1251.csv' OPTIONS (DELIMITER = ';', ENCODING = 'WIN1251', DECIMAL = ',');
SELECT NAME, AMOUNT, X, ID, OCTET_LENGTH(NAME) FROM P;

-- BOM: UTF8, into a view
IMPORT INTO V FROM CSV 'bom.csv' OPTIONS (HEADER = TRUE);
SELECT NAME, AMOUNT FROM P ORDER BY ID;

-- many rows: batches, commit, no batch
IMPORT INTO M FROM CSV 'many.csv' OPTIONS (COMMIT = 1000);
SELECT COUNT(*), MIN(ID), MAX(ID) FROM M;
IMPORT INTO M FROM CSV 'many.csv' OPTIONS (BATCH = 0, SKIP = 2500);
SELECT COUNT(*), MAX(ID) FROM M;

-- EXEC SQL with expressions; update
PREPARE ins AS INSERT INTO M (ID, S) VALUES (? + 10000, UPPER(?));
EXEC SQL ins FROM CSV 'upd.csv';
SELECT ID, S FROM M WHERE ID > 10000 ORDER BY ID;
PREPARE upd AS UPDATE T SET S = ? WHERE ID = ?;
EXEC SQL upd FROM CSV 'upd2.csv';
SELECT ID, S FROM T WHERE ID IN (1, 3);
EXEC SQL upd FROM CSV 'upd.csv';
PREPARE upd2 AS UPDATE T SET S = ?2 WHERE ID = ?1;
PREPARE upd2 AS UPDATE T SET S = :S WHERE ID = :ID;
PREPARE sel AS SELECT * FROM T WHERE ID = ?;
EXEC SQL sel FROM CSV 'upd.csv';
PREPARE upd3 AS UPDATE T SET S = ? WHERE ID = CAST(? AS INT) - 0;
EXEC SQL upd3 FROM CSV 'upd.csv' OPTIONS (BATCH = 0);

-- errors of the commands
IMPORT INTO T FROM CSV 'quote.csv';
IMPORT INTO T FROM CSV 'missing.csv';
IMPORT INTO NOSUCH FROM CSV 'a.csv';
IMPORT INTO T FROM CSV 'a.csv' OPTIONS (SEP = ';');
IMPORT T FROM CSV 'a.csv';
EXEC SQL nosuch FROM CSV 'a.csv';
EXEC SQL ins;
IMPORT INTO T FROM CSV 'a.csv';
IMPORT INTO T (ID) FROM CSV 'a.csv' OPTIONS (HEADER);
ROLLBACK;
SELECT COUNT(*) FROM T;
