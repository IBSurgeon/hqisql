SET ECHO ON;
SET TIME ZONE 'UTC';
CREATE DATABASE 'imp2.fdb' DEFAULT CHARACTER SET UTF8;
CREATE TABLE PQ (ID INT PRIMARY KEY, NAME VARCHAR(20), AMOUNT NUMERIC(10,2), D DATE, TS TIMESTAMP,
	TSU TIMESTAMP WITH TIME ZONE, FLAG BOOLEAN, DATA VARBINARY(10), U CHAR(16) CHARACTER SET OCTETS,
	F DOUBLE PRECISION, T TIME);
CREATE TABLE US (ID INT, U VARCHAR(36));
CREATE TABLE B (ID INT PRIMARY KEY, NAME VARCHAR(10));
CREATE TABLE CP (ID INT, NAME VARCHAR(30), AMOUNT NUMERIC(10,2), D DATE, TS TIMESTAMP,
	TSU TIMESTAMP WITH TIME ZONE, FLAG BOOLEAN);
CREATE TABLE BIG (ID INT, NAME VARCHAR(20), AMOUNT NUMERIC(12,2));
COMMIT;

-- PARQUET: all the columns by name
IMPORT INTO PQ FROM PARQUET 't.parquet';
SELECT * FROM PQ ORDER BY ID;

-- PARQUET: zstd, page v2; gzip without a dictionary; some columns
DELETE FROM PQ;
IMPORT INTO PQ FROM PARQUET 't_zstd.parquet';
SELECT COUNT(*), COUNT(NAME), MAX(TSU) FROM PQ;
DELETE FROM PQ;
IMPORT INTO PQ (ID, NAME, U) FROM PARQUET 't_gzip.parquet' OPTIONS (SKIP = 1);
SELECT ID, NAME, U, D FROM PQ ORDER BY ID;

-- UUID into a text column
PREPARE INS_U AS INSERT INTO US (ID, U) VALUES (?, ?);
EXEC SQL INS_U FROM PARQUET 'u.parquet';
EXEC SQL INS_U FROM AVRO 'u.avro';
SELECT * FROM US;

-- errors: no such column, a list column, a bad option
IMPORT INTO PQ (ID, NOPE) FROM PARQUET 't.parquet';
IMPORT INTO PQ FROM PARQUET 'list.parquet';
IMPORT INTO PQ FROM PARQUET 't.parquet' OPTIONS (HEADER);
IMPORT INTO PQ FROM PARQUET 'missing.parquet';
IMPORT INTO PQ FROM AVRO 't.parquet';

-- bad rows: a duplicate key, a long name
IMPORT INTO B FROM PARQUET 'bad.parquet' OPTIONS (ERRORS = 5, BATCH = 2);
SELECT * FROM B ORDER BY ID;
DELETE FROM B;
IMPORT INTO B FROM PARQUET 'bad.parquet';
SELECT COUNT(*) FROM B;

-- AVRO
DELETE FROM PQ;
IMPORT INTO PQ FROM AVRO 't.avro';
SELECT * FROM PQ ORDER BY ID;
DELETE FROM PQ;
IMPORT INTO PQ (ID, TSU, NAME) FROM AVRO 't_deflate.avro';
SELECT ID, NAME, TSU FROM PQ ORDER BY ID;

-- COPY
IMPORT INTO CP FROM COPY 't.txt';
SELECT ID, NAME, AMOUNT, D, TS, TSU, FLAG FROM CP ORDER BY ID;
DELETE FROM CP;
IMPORT INTO CP (ID, NAME) FROM COPY 'h.txt' OPTIONS (HEADER, DELIMITER = '|', NULL = 'NULL');
SELECT ID, NAME, NAME IS NULL FROM CP ORDER BY ID;
PREPARE INS_CP AS INSERT INTO CP (ID, NAME) VALUES (?, ? || '!');
DELETE FROM CP;
EXEC SQL INS_CP FROM COPY 'h.txt' OPTIONS (SKIP = 1, DELIMITER = '|');
SELECT ID, NAME FROM CP ORDER BY ID;

-- many rows
IMPORT INTO BIG FROM PARQUET 'big.parquet' OPTIONS (BATCH = 5000);
SELECT COUNT(*), SUM(AMOUNT), MAX(NAME) FROM BIG;
